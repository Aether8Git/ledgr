// Generates supabase/seed.sql from the seed rule library in src/engine/rules.ts.
// Run: npm run seed:sql
import { writeFileSync } from "node:fs";
import { SEED_RULES } from "../src/engine/rules";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = SEED_RULES.map(
  (r) =>
    `(${q(r.id)}, ${r.version}, ${q(r.category)}, ${q(r.verificationStatus)}, ${r.enabled}, ${q(JSON.stringify(r))}::jsonb)`,
);
const versions = SEED_RULES.map((r) => `(${q(r.id)}, ${r.version}, ${q(JSON.stringify(r))}::jsonb, ${q(r.history[0].summary)})`);
const sql = `-- GENERATED by scripts/gen-seed.ts — do not edit by hand.
-- Seed rule library. All rules are 'reference_cited' or 'draft' until validated through approve_rule_change().
insert into public.rules (id, version, category, verification_status, enabled, definition) values
${rows.join(",\n")}
on conflict (id) do nothing;

insert into public.rule_versions (rule_id, version, definition, summary) values
${versions.join(",\n")}
on conflict do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${SEED_RULES.length} rules to supabase/seed.sql`);
